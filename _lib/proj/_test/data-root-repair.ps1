[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 2.0

$ProjRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
. (Join-Path $ProjRoot '_core\engine.ps1')
. (Join-Path $ProjRoot '.dev\setup\_lib\foundation.ps1')

function Assert-ProjDataRootRepairTest {
    param(
        [Parameter(Mandatory = $true)][bool]$Condition,
        [Parameter(Mandatory = $true)][string]$Message
    )
    if (-not $Condition) {
        throw "Assertion failed: $Message"
    }
}

$TestBase = [IO.Path]::GetFullPath(
    (Join-Path $ProjRoot '..\..\data\_test')
)
[void][IO.Directory]::CreateDirectory($TestBase)
$TemporaryRoot = Join-Path $TestBase (
    "swawkit-proj-data-repair-$([Guid]::NewGuid().ToString('N'))"
)
$ProjHome = Join-Path $TemporaryRoot 'swaw-kit-home'
$ProjectRoot = Join-Path $TemporaryRoot 'project'
$ActionRoot = Join-Path $ProjectRoot '.swaw'
$LegacyLink = Join-Path $ProjectRoot 'data'
$RepairEnvironmentLink = ''
$SetupEnvironmentLink = ''
$PreviousDataRoot = [Environment]::GetEnvironmentVariable(
    'SWAWKIT_PROJ_DATA_ROOT',
    'Process'
)

try {
    [void][IO.Directory]::CreateDirectory($ProjHome)
    [void][IO.Directory]::CreateDirectory($ProjectRoot)
    [Environment]::SetEnvironmentVariable(
        'SWAWKIT_PROJ_DATA_ROOT',
        $null,
        'Process'
    )

    $OldEntry = Join-Path $ProjectRoot 'locked.cmd'
    [IO.File]::WriteAllText($OldEntry, '@echo off')
    $OldDataRoot = Resolve-ProjProjectDataRoot `
        -ProjHome $ProjHome `
        -ProjectRoot $ProjectRoot `
        -ActionRoot $ActionRoot `
        -EntryFile $OldEntry
    $OldEnvironmentRoot = Join-Path $OldDataRoot 'dev_env'
    [void][IO.Directory]::CreateDirectory($OldEnvironmentRoot)
    $CmdPath = Join-Path $OldEnvironmentRoot 'env.cmd'
    $Ps1Path = Join-Path $OldEnvironmentRoot 'env.ps1'
    $StatePath = Join-Path $OldEnvironmentRoot '_state.json'
    [IO.File]::WriteAllText(
        $CmdPath,
        "rem Generated by Swaw Kit Proj.`r`n" +
        "set `"SWAWKIT_DEV_ENV_ROOT=$OldEnvironmentRoot`"`r`n"
    )
    [IO.File]::WriteAllText(
        $Ps1Path,
        "# Generated by Swaw Kit Proj.`r`n" +
        "`$env:SWAWKIT_DEV_ENV_ROOT = " +
        "'$($OldEnvironmentRoot.Replace("'", "''"))'`r`n"
    )
    [IO.File]::WriteAllText($StatePath, '{}')

    $NewEntry = Join-Path $ProjectRoot 'recovered.cmd'
    [IO.File]::Move($OldEntry, $NewEntry)
    $NewDataRoot = Join-Path $ProjHome 'data\proj.recovered'
    [Environment]::SetEnvironmentVariable(
        'SWAWKIT_PROJ_DATA_ROOT',
        $null,
        'Process'
    )
    [void](Resolve-ProjProjectDataRoot `
        -ProjHome $ProjHome `
        -ProjectRoot $ProjectRoot `
        -ActionRoot $ActionRoot `
        -EntryFile $NewEntry `
        -ClaimApprover { return $true })

    # Model a process that was killed after the rename binding committed but
    # before every stale publication file was removed. The next Direct resolve
    # must derive staleness from the generated file itself, not the lost old path.
    $NewEnvironmentRoot = Join-Path $NewDataRoot 'dev_env'
    [void][IO.Directory]::CreateDirectory($NewEnvironmentRoot)
    [IO.File]::WriteAllText(
        (Join-Path $NewEnvironmentRoot 'env.ps1'),
        "# Generated by Swaw Kit Proj.`r`n" +
        "`$env:SWAWKIT_DEV_ENV_ROOT = " +
        "'$($OldEnvironmentRoot.Replace("'", "''"))'`r`n"
    )
    [IO.File]::WriteAllText(
        (Join-Path $NewEnvironmentRoot '_state.json'),
        '{}'
    )
    [Environment]::SetEnvironmentVariable(
        'SWAWKIT_PROJ_DATA_ROOT',
        $null,
        'Process'
    )
    $RecoveredDataRoot = Resolve-ProjProjectDataRoot `
        -ProjHome $ProjHome `
        -ProjectRoot $ProjectRoot `
        -ActionRoot $ActionRoot `
        -EntryFile $NewEntry
    Assert-ProjDataRootRepairTest `
        -Condition ($RecoveredDataRoot -ceq $NewDataRoot -and
            -not [IO.Directory]::Exists($OldDataRoot) -and
            -not [IO.File]::Exists((Join-Path $NewDataRoot 'dev_env\env.cmd')) -and
            -not [IO.File]::Exists((Join-Path $NewDataRoot 'dev_env\env.ps1')) -and
            -not [IO.File]::Exists((Join-Path $NewDataRoot 'dev_env\_state.json'))) `
        -Message 'a partial ClaimRename publication was not repaired on retry'

    # A recognized generated publication with an unreadable root is damaged
    # state, not an ownership ambiguity. It must be cleared so .dev.setup can
    # be dispatched on the same invocation path.
    [void][IO.Directory]::CreateDirectory($NewEnvironmentRoot)
    [IO.File]::WriteAllText(
        (Join-Path $NewEnvironmentRoot 'env.ps1'),
        "# Generated by Swaw Kit Proj.`r`n" +
        "`$env:SWAWKIT_DEV_ENV_ROOT = ''`r`n"
    )
    [IO.File]::WriteAllText(
        (Join-Path $NewEnvironmentRoot '_state.json'),
        '{}'
    )
    [Environment]::SetEnvironmentVariable(
        'SWAWKIT_PROJ_DATA_ROOT',
        $null,
        'Process'
    )
    $DamagedPublicationDataRoot = Resolve-ProjProjectDataRoot `
        -ProjHome $ProjHome `
        -ProjectRoot $ProjectRoot `
        -ActionRoot $ActionRoot `
        -EntryFile $NewEntry
    Assert-ProjDataRootRepairTest `
        -Condition ($DamagedPublicationDataRoot -ceq $NewDataRoot -and
            -not [IO.File]::Exists(
                (Join-Path $NewEnvironmentRoot 'env.ps1')
            ) -and
            -not [IO.File]::Exists(
                (Join-Path $NewEnvironmentRoot '_state.json')
            )) `
        -Message 'an invalid generated environment root blocked automatic repair'

    # DataRoot is owned, but its managed environment child is a separate
    # destructive boundary. Never follow a junction while repairing it.
    if ([IO.Directory]::Exists($NewEnvironmentRoot)) {
        [IO.Directory]::Delete($NewEnvironmentRoot)
    }
    $ExternalPublication = Join-Path $TemporaryRoot 'external-publication'
    [void][IO.Directory]::CreateDirectory($ExternalPublication)
    $ExternalSentinel = Join-Path $ExternalPublication 'sentinel.txt'
    [IO.File]::WriteAllText($ExternalSentinel, 'preserve')
    $RepairEnvironmentLink = $NewEnvironmentRoot
    [void](New-Item `
        -ItemType Junction `
        -Path $RepairEnvironmentLink `
        -Target $ExternalPublication)
    [Environment]::SetEnvironmentVariable(
        'SWAWKIT_PROJ_DATA_ROOT',
        $null,
        'Process'
    )
    $RejectedRepairJunction = $false
    try {
        [void](Resolve-ProjProjectDataRoot `
            -ProjHome $ProjHome `
            -ProjectRoot $ProjectRoot `
            -ActionRoot $ActionRoot `
            -EntryFile $NewEntry)
    } catch {
        $RejectedRepairJunction =
            $_.Exception.Message -like '*environment root*reparse point*'
    }
    Assert-ProjDataRootRepairTest `
        -Condition ($RejectedRepairJunction -and
            [IO.File]::Exists($ExternalSentinel)) `
        -Message 'DataRoot repair followed a managed environment junction'
    [IO.Directory]::Delete($RepairEnvironmentLink)
    $RepairEnvironmentLink = ''

    # Setup and all module helpers enter through New-ProjDevContext. The same
    # controlled-root check must reject a junction before installation writes.
    $SetupDataRoot = Join-Path $TemporaryRoot 'setup-data'
    [void][IO.Directory]::CreateDirectory($SetupDataRoot)
    $SetupExternalRoot = Join-Path $TemporaryRoot 'setup-external'
    [void][IO.Directory]::CreateDirectory($SetupExternalRoot)
    $SetupSentinel = Join-Path $SetupExternalRoot 'sentinel.txt'
    [IO.File]::WriteAllText($SetupSentinel, 'preserve')
    $SetupEnvironmentLink = Join-Path $SetupDataRoot 'dev_env'
    [void](New-Item `
        -ItemType Junction `
        -Path $SetupEnvironmentLink `
        -Target $SetupExternalRoot)
    $RejectedSetupJunction = $false
    try {
        [void](New-ProjDevContext `
            -ProjectRoot $ProjectRoot `
            -DataRoot $SetupDataRoot `
            -CacheDataRoot (Join-Path $TemporaryRoot 'setup-cache'))
    } catch {
        $RejectedSetupJunction =
            $_.Exception.Message -like '*environment root*reparse point*'
    }
    Assert-ProjDataRootRepairTest `
        -Condition ($RejectedSetupJunction -and
            [IO.File]::Exists($SetupSentinel)) `
        -Message 'setup accepted a managed environment junction'
    [IO.Directory]::Delete($SetupEnvironmentLink)
    $SetupEnvironmentLink = ''

    [Environment]::SetEnvironmentVariable(
        'SWAWKIT_PROJ_DATA_ROOT',
        $null,
        'Process'
    )
    $ExternalData = Join-Path $TemporaryRoot 'external-data'
    [void][IO.Directory]::CreateDirectory($ExternalData)
    [void](New-Item `
        -ItemType Junction `
        -Path $LegacyLink `
        -Target $ExternalData)
    $RejectedLegacyJunction = $false
    try {
        [void](Get-ProjDataRootDirectories -DataDirectory $LegacyLink)
    } catch {
        $RejectedLegacyJunction = $_.Exception.Message -like '*reparse point*'
    }
    Assert-ProjDataRootRepairTest `
        -Condition ($RejectedLegacyJunction -and
            [IO.Directory]::Exists($ExternalData)) `
        -Message 'a legacy project data junction crossed the migration boundary'
} finally {
    [Environment]::SetEnvironmentVariable(
        'SWAWKIT_PROJ_DATA_ROOT',
        $PreviousDataRoot,
        'Process'
    )
    foreach ($Link in @($RepairEnvironmentLink, $SetupEnvironmentLink)) {
        if (-not [string]::IsNullOrWhiteSpace($Link) -and
            [IO.Directory]::Exists($Link)) {
            [IO.Directory]::Delete($Link)
        }
    }
    if ([IO.Directory]::Exists($LegacyLink)) {
        [IO.Directory]::Delete($LegacyLink)
    }
    if ([IO.Directory]::Exists($TemporaryRoot)) {
        [IO.Directory]::Delete($TemporaryRoot, $true)
    }
}

Write-Host '[PASS] Proj DataRoot repair and reparse boundary' `
    -ForegroundColor Green
$global:LASTEXITCODE = 0
